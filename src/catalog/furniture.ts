/**
 * 기본 가구 카탈로그. 치수는 mm (가로 width × 깊이 depth × 높이 height).
 * 가구의 "앞"은 회전 0일 때 화면 아래쪽(+y)이고, 등받이·머리판은 위쪽(-y)에 있다.
 */
export type FurnitureCategory =
  | "bed"
  | "sofa"
  | "table"
  | "chair"
  | "storage"
  | "kitchen"
  | "appliance"
  | "hobby"
  | "etc";

export type FurnitureSymbol = "bed" | "sofa" | "round" | "rug" | "hanger" | "l-shape" | "plain";

export type CatalogItem = {
  id: string;
  name: string;
  category: FurnitureCategory;
  width: number;
  depth: number;
  height: number;
  color: string;
  symbol: FurnitureSymbol;
  /** 카탈로그 목록에는 보이지 않음 (직접 만든 가구) */
  hidden?: boolean;
  /** 쓰려면 비워 둬야 하는 공간 (mm). 앞은 회전 0일 때 +y 쪽 */
  clearance?: Clearance;
};

export type Clearance = {
  front?: number;
  back?: number;
  side?: number;
  /** either: 양옆 중 한쪽만 비어 있으면 됨 (침대) / both: 양쪽 모두 */
  sideMode?: "either" | "both";
};

